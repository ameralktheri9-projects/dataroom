export const dictionaries: Record<Lang, VisitorDict> = { en, ar };

export function pickLang(cookieValue: string | undefined, acceptLanguage: string | null): Lang {
  if (cookieValue === "ar" || cookieValue === "en") return cookieValue;
  return acceptLanguage?.toLowerCase().startsWith("ar") ? "ar" : "en";
}
